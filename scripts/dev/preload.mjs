// Keeps the preload block of app/index.html in step with the code.
//
//   node scripts/dev/preload.mjs           # rewrite the block
//   node scripts/dev/preload.mjs --check   # exit 1 if it is out of date (tests/preload.test.mjs)
//
// The game has no build step: the browser finds each ES module only when the file that imports
// it has arrived, and every stylesheet only when app.css has. On a phone that is one network
// round trip per import level (about ten of them). The block lists the whole static import
// graph of the first screen (ui/main.js + the Home screen) as <link rel="modulepreload"> and
// the stylesheets app.css imports as <link rel="preload" as="style">, so everything is
// requested at once. Lazy screens are not listed; Home warms the next ones when idle.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = resolve(fileURLToPath(new URL('../../app/', import.meta.url)));
const INDEX = `${APP}/index.html`;
const START = '<!-- preload:start (generated by scripts/dev/preload.mjs — npm run preload) -->';
const END = '<!-- preload:end -->';
// The first screen: the entry module and the default route's screen (ui/routes.js).
const ENTRIES = ['ui/main.js', 'ui/screens/home/home.js'];

/** Static imports and re-exports of a module source (dynamic import() is lazy by design). */
function staticImports(source) {
  const found = [];
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  for (const m of code.matchAll(
    /(?:^|[\n;])\s*(?:import|export)\s+(?:[^'"()]*?\sfrom\s+)?['"]([^'"]+)['"]/g,
  ))
    found.push(m[1]);
  return found;
}

export function buildBlock(html = readFileSync(INDEX, 'utf8')) {
  const importMap = JSON.parse(html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]);
  const locate = (specifier, from) => {
    if (importMap.imports[specifier]) return posix.normalize(importMap.imports[specifier]);
    if (!specifier.startsWith('.')) throw Error(`Unmapped import "${specifier}" in ${from}`);
    return posix.normalize(posix.join(dirname(from), specifier));
  };
  const modules = [],
    seen = new Set(),
    queue = [...ENTRIES];
  while (queue.length) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    seen.add(file);
    if (!existsSync(`${APP}/${file}`)) throw Error(`Missing module ${file}`);
    modules.push(file);
    for (const specifier of staticImports(readFileSync(`${APP}/${file}`, 'utf8')))
      queue.push(locate(specifier, file));
  }
  const sheet = 'ui/styles/app.css',
    styles = [...readFileSync(`${APP}/${sheet}`, 'utf8').matchAll(/@import url\('([^']+)'\)/g)].map(
      m => posix.normalize(posix.join(dirname(sheet), m[1])),
    );
  const lines = [
    START,
    ...styles.map(href => `<link rel="preload" as="style" href="./${href}" />`),
    // The entry module is requested by its own <script>; preload what it pulls in.
    ...modules.slice(1).map(href => `<link rel="modulepreload" href="./${href}" />`),
    END,
  ];
  return { block: lines.join('\n    '), modules: modules.length, styles: styles.length };
}

export function withBlock(html, block) {
  const start = html.indexOf(START),
    end = html.indexOf(END);
  if (start < 0 || end < 0) throw Error('app/index.html has no preload markers');
  return html.slice(0, start) + block + html.slice(end + END.length);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = readFileSync(INDEX, 'utf8'),
    { block, modules, styles } = buildBlock(html),
    next = withBlock(html, block);
  if (process.argv.includes('--check')) {
    if (next !== html) {
      console.error('app/index.html preload block is out of date: run `npm run preload`');
      process.exitCode = 1;
    } else console.log(`preload block is current (${modules} modules, ${styles} stylesheets)`);
  } else {
    if (next !== html) writeFileSync(INDEX, next);
    console.log(
      `${next !== html ? 'updated' : 'unchanged'}: ${modules} modules, ${styles} stylesheets`,
    );
  }
}

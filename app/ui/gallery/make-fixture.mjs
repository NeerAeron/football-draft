// Regenerates app/ui/gallery/fixture.js — a handful of real catalog players as PlayerView
// objects for the component gallery. Dev tool (Node ≥ 22), not loaded by any page:
//   node app/ui/gallery/make-fixture.mjs
/* global process, console, URL */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { decodeCatalog, indexCatalog } from '../../core/players/catalog-codec.js';
import { reconcileCatalog } from '../../core/players/catalog-derived.js';
import { playerView } from '../lib/player-view.js';

const here = path => fileURLToPath(new URL(path, import.meta.url));
const file = JSON.parse(readFileSync(here('../../data/catalog.v3.json'), 'utf8'));
const c = indexCatalog(reconcileCatalog(decodeCatalog(file)));

const nationByName = new Map(c.nations.map(n => [n.name, n]));
const teamById = new Map(c.teams.map(t => [t.id, t]));
const leagueById = new Map(c.leagues.map(l => [l.id, l]));
const ovr = p => p.overall ?? p.sourceOverall;

const view = p => {
  const team = teamById.get(p.source?.clubId);
  const nation = nationByName.get(p.source?.nationality);
  return playerView(p, {
    team,
    league: leagueById.get(p.source?.leagueId || team?.leagueId),
    nation: nation ? { name: nation.name, code: nation.code } : undefined,
  });
};

const find = (name, nationality) => {
  const hits = c.players.filter(p => p.name === name && p.source?.nationality === nationality);
  if (!hits.length) throw new Error(`fixture: no player ${name} (${nationality}) in the catalog`);
  return hits.sort((a, b) => ovr(b) - ovr(a))[0];
};

// A 4-3-3 XI of superstars (pitch demo, in FORMATIONS['433'] slot order) …
const xi = [
  ['Alisson', 'Brazil'],
  ['Nuno Mendes', 'Portugal'],
  ['W. Saliba', 'France'],
  ['V. van Dijk', 'Netherlands'],
  ['A. Hakimi', 'Morocco'],
  ['Rodri', 'Spain'],
  ['Pedri', 'Spain'],
  ['J. Bellingham', 'England'],
  ['Vini Jr.', 'Brazil'],
  ['E. Haaland', 'Norway'],
  ['M. Salah', 'Egypt'],
].map(([name, nation]) => find(name, nation));

// … one player per lower tier band, picked deterministically, and the best club-less player.
const band = (lo, hi, pos) =>
  c.players
    .filter(p => ovr(p) >= lo && ovr(p) <= hi && p.primaryPosition === pos && p.source?.club)
    .sort((a, b) => ovr(b) - ovr(a) || a.profileId.localeCompare(b.profileId))[0];
const extra = [band(80, 84, 'CM'), band(74, 79, 'ST'), band(68, 73, 'CB'), band(55, 67, 'LM')];
extra.push(c.players.filter(p => !p.source?.club).sort((a, b) => ovr(b) - ovr(a))[0]);

const players = [...xi, ...extra].filter(Boolean).map(view);
const leagues = c.leagues
  .filter(l => l.logo)
  .slice(0, 6)
  .map(l => ({ name: l.name, logo: l.logo, tier: l.tier }));
const clubs = [
  'Liverpool',
  'Real Madrid',
  'Juventus',
  'Celtic',
  'Newcastle United',
  'Borussia Dortmund',
]
  .map(name => c.teams.find(t => t.name === name))
  .filter(Boolean)
  .map(t => ({ name: t.name, colors: [t.primary, t.secondary].filter(Boolean) }));
const nations = [
  'Brazil',
  'Argentina',
  'France',
  'Japan',
  'England',
  "Côte d'Ivoire",
  'Scotland',
  'Korea Republic',
]
  .map(name => nationByName.get(name))
  .filter(Boolean)
  .map(n => ({ name: n.name, code: n.code }));

const out = here('./fixture.js');
const source = `// Generated by app/ui/gallery/make-fixture.mjs from app/data/catalog.v3.json — do not edit.
// Real players (data by rovnez, CC BY 4.0; see Settings → Credits) as PlayerView objects
// (app/ui/lib/player-view.js) for the component gallery.
export const PLAYERS = ${JSON.stringify(players)};
export const LEAGUES = ${JSON.stringify(leagues)};
export const CLUBS = ${JSON.stringify(clubs)};
export const NATIONS = ${JSON.stringify(nations)};
`;
const options = { ...(await prettier.resolveConfig(out)), filepath: out };
writeFileSync(out, await prettier.format(source, options));
console.log(`${players.length} players → ${out}`);
process.exitCode = 0;
